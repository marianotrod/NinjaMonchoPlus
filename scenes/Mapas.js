const _ = '';
const L = 'CR01TL', R = 'CR01TR', P = 'CP01TC'; 
const H1 = 'CH01TC', H2 = 'CH02TC', H3 = 'CH03TC'; 
const M1 = 'M1', C2 = 'C2';

// 🚀 TRADUCTOR VISUAL: Convierte tu "dibujo" en la matriz que usa Phaser
function parsearMapa(dibujo) {
    return dibujo.trim().split('\n').map(linea => 
        linea.trim().split('').map(char => {
            if (char === 'L') return L;
            if (char === 'R') return R;
            if (char === 'P') return P;
            if (char === '.') return _;
            if (char === '1') return H1;
            if (char === '2') return H2;
            if (char === '3') return H3;
            if (char === 'M') return M1;
            if (char === 'C') return C2;
            return _;
        })
    );
}

